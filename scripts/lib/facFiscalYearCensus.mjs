/**
 * A national, first-party census of LOCAL GOVERNMENT fiscal calendars, built
 * from the Federal Audit Clearinghouse.
 *
 * ⚠ NO SHEBANG. This is a library, never executed — and `tests/waSao.test.mjs`
 * fails the build if any module a test imports starts with `#!`.
 *
 * ── What this is ────────────────────────────────────────────────────────────
 * Every government expending >= $750k of federal awards files a Single Audit,
 * and the FAC publishes the AUDITED PERIOD of that filing — the auditee's own
 * submission, made under federal penalty. Censusing it answers "what calendar
 * does this government run" for the whole country at once, instead of one
 * charter or ACFR at a time.
 *
 * `docs/fac/fac-local-fiscal-year-ends.csv` covers **audit years 1998-2026**
 * across **56 jurisdictions**, and is regenerated by
 * `scripts/buildFacFiscalYearCensus.mjs` from two free bulk downloads (no API
 * key, no rate limit). See that file for the download URLs and every filter.
 *
 * ── Why a state's "usual" month is never an entity's month ──────────────────
 * This census exists because the generalisation keeps being wrong, and the
 * national measurements show how badly:
 *
 *   • MICHIGAN municipalities are modally JULY — but Michigan TOWNSHIPS are
 *     APRIL, and 55 Michigan municipalities run MARCH.
 *   • ILLINOIS municipalities are modally MAY. Illinois COUNTIES are DECEMBER.
 *   • UTAH counties are JANUARY while Utah cities are JULY.
 *   • TEXAS locals are modally OCTOBER — but HOUSTON is July, EL PASO is
 *     September, 42 counties are January, and HARRIS COUNTY ran MARCH until it
 *     switched to October in 2023.
 *   • NEW YORK villages are largely JUNE while its cities and counties are
 *     JANUARY.
 *   • CALIFORNIA cities are July with five October exceptions, two of which are
 *     general-law cities that the old charter-city framing could never have
 *     found.
 *
 * ⚠⚠ SO A STATE-WIDE MONTH IS A DEFAULT, NEVER A FACT ABOUT AN ENTITY.
 * `dominantMonthFor()` is MEASURED per (state, kind) rather than declared, and
 * `censusMonthFor()` — the per-entity fact — is what a loader must consult.
 *
 * ── What a census CANNOT tell you ───────────────────────────────────────────
 *   (a) It begins at audit year 1998. A change made earlier is invisible.
 *       Every TT row is FY2003 or later, so the window covers our data.
 *   (b) An entity below the $750k federal threshold NEVER FILES, so absence is
 *       not evidence of anything. Nationally that is most small towns.
 *   (c) A period's END does not reveal its LENGTH. In a changeover year the
 *       audit covers a SHORT stub that still begins in the OLD month, so the
 *       month inferred from the end is wrong in exactly that year — see
 *       `changeoverYears()`, and the `other`/`biennial` rows which record a
 *       stub's length where the federal record states it.
 */

import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const REPO = path.resolve(HERE, '..', '..');

/** The single national evidence file. */
export const EVIDENCE_CSV = path.join(REPO, 'docs', 'fac', 'fac-local-fiscal-year-ends.csv');

/**
 * ⚠ 1998 ONLY BECAUSE THE HISTORIC HALF IS LOADED. The FAC publishes 2016+ and
 * 1998-2015 as two separate downloads with different schemas; a census built
 * from the modern file alone starts at 2016, which was this census's blind spot
 * while TT held rows back to FY2003.
 */
export const WINDOW = { firstAuditYear: 1998, lastAuditYear: 2026 };

/** Measured when the national census was built. A move here means the federal record moved. */
export const BASELINE = { rows: 17921, entities: 16091, jurisdictions: 52, exceptions: 1281 };

