/**
 * Detect days a publisher exported TWICE.
 *
 * ── ⚠⚠⚠ WHY THIS EXISTS ───────────────────────────────────────────────────
 *
 * `column_mapping.dedup = 'occurrence'` (PR #334) keys the Nth copy of an
 * identical row as `<hash>#N` instead of collapsing it. That is correct when a
 * government really did the same thing N times — McKinney's uniform-rental
 * invoice has 132 identical $13.60 garment lines, and a content hash kept one.
 *
 * It is CATASTROPHIC when the publisher's export wrote the same day twice,
 * because then every duplicate is money that was never spent, and `occurrence`
 * faithfully loads all of it.
 *
 * ⚠⚠ THE PUBLISHER'S OWN TOTAL ROW CANNOT CATCH THIS. The oracle that proved
 * the McKinney repair — the register's `Total` line — is generated by the same
 * report that generated the data rows. A doubled export doubles BOTH, and the
 * two still agree to the cent. The only check that works is the shape of the
 * data itself.
 *
 * ── ⭐⭐ THE TEST: EVENNESS, NOT CONTENT ───────────────────────────────────
 *
 * For one publication date, count how many times each distinct row appears.
 *
 *                                    doubled export   an ordinary day
 *   distinct rows with an EVEN count      100%           0.4 - 1.8%
 *   rows appearing EXACTLY ONCE             0              ~99%
 *
 * A real payment day always has rows that happen only once. Literally zero is
 * not something a city can do by coincidence; it is only possible if the day's
 * records were emitted twice. Measured 2026-11-04:
 *
 *   Frisco 2019-06-06    496 rows, 243 distinct, 100% even, 0 appear once
 *   Frisco 2019-05     2,105 rows, 2,072 distinct, 1.3% even   <- baseline
 *   Plano  2022-03-18  1,082 rows, 532 distinct, 100% even, 0 appear once
 *   Plano  2022-06     2,222 rows, 2,192 distinct, 0.4% even   <- baseline
 *
 * ── ⚠ THIS CORRECTS A CLAIM IN THE MIGRATION THAT INTRODUCED THE POLICY ────
 *
 * supabase/migrations/20261104200000_mckinney_occurrence_dedup.sql says Frisco
 * "looks like McKinney ... but publishes no Total row, so it has no oracle".
 * That reasoning is wrong. Frisco needs no oracle: four days in June 2019 are
 * 100% even with no row appearing once, so $14.97M of its apparent loss is an
 * export artifact and the content hash is already doing the right thing.
 *
 * ⛔ DO NOT switch Frisco or Plano to 'occurrence'. Across their 15 sources,
 * $39,075,332.74 of the discarded money is export doubling. Only
 * $4,272,431.64 is the ordinary background of genuinely repeated payments.
 */
import { hashRow } from './xlsxRows.mjs';

/**
 * ⚠ A day needs enough rows before "every count is even" means anything. On a
 * two-row day, two identical rows are even and nothing appears once — which is
 * exactly the shape we are looking for, and proves nothing at all.
 */
export const MIN_ROWS_TO_CERTIFY = 20;

/**
 * ⚠ NOT 1.00. Frisco 2019-06-04 is 272 of 273 distinct rows even — one row
 * that genuinely occurred three times rides along inside a doubled day. A rule
 * demanding perfection would miss the largest single event we found.
 */
export const MIN_EVEN_SHARE = 0.95;

/**
 * ⚠⚠ ONLY TWO CONDITIONS DECIDE, and that is deliberate.
 *
 * An earlier version also gated on "at least 40% of rows are extra copies" and
 * "at most 5% of distinct rows appear exactly once". Mutation testing showed
 * both were dead: a row appearing once has an ODD count, so
 * `evenShare >= 0.95` already forces `onceShare <= 0.05`; and `evenShare >=
 * 0.95` means nearly every distinct row is duplicated, which forces the extra
 * share above 0.48. Two gates that can never fire are two gates nobody is
 * testing, so they were removed.
 *
 * Both statistics are still COMPUTED and REPORTED, because "not one row on
 * this day appears exactly once" is how a human recognises the finding — it is
 * the sentence that makes the claim checkable, just not the one that decides.
 */

/**
 * ⚠⚠ rows ÷ distinct. A day written twice sits at ~2.0 — Frisco 2019-06-04 is
 * 563/273 = 2.06, Plano 2022-03-18 is 1,082/532 = 2.03.
 *
 * Without this, ONE row repeated many times passes every other test: Frisco
 * 2023-04-04 is 84 rows of a single distinct line, so 100% of its distinct rows
 * have an even count and none appears once. That is a many-line invoice, the
 * very thing `occurrence` exists to keep — the opposite of a doubled export,
 * and the first version of this check called it a doubling.
 */
export const MAX_MEAN_MULTIPLICITY = 2.5;

/**
 * A SMALL day with the doubled shape counts only if it sits within this many
 * days of a certified big one. Alone it proves nothing; beside a 1,082-row day
 * that is 100% even it is the same export event spilling over. This is what
 * catches Plano's TMRS pair (2022-03-15, two rows, $3,482,404.02 each).
 */
export const SPILLOVER_WINDOW_DAYS = 7;

/**
 * Normalise a cell to a YYYY-MM-DD bucket.
 *
 * ⚠ Handles the two shapes the loaders actually produce: a Date from ExcelJS,
 * and `M/D/YYYY h:mm:ss AM` from a CSV. A naive `String(v).slice(0, 10)` turns
 * `9/30/2024 12:00:00 AM` into `9/30/2024 ` and buckets correctly only by
 * accident, so it is spelled out.
 */
export function dayKey(value) {
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  if (value === null || value === undefined) return '';
  const s = String(value).trim();
  const slash = s.match(/^(\d{1,2})\/(\d{1,2})\/(\d{4})/);
  if (slash) return `${slash[3]}-${slash[1].padStart(2, '0')}-${slash[2].padStart(2, '0')}`;
  const iso = s.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (iso) return iso[0];
  return s.slice(0, 10);
}

function parseAmountSafe(v) {
  if (typeof v === 'number') return Number.isFinite(v) ? v : 0;
  if (v === null || v === undefined) return 0;
  const s = String(v).trim();
  const neg = /^\(.*\)$/.test(s);
  const n = Number.parseFloat(s.replace(/[^0-9.-]/g, ''));
  if (!Number.isFinite(n)) return 0;
  return neg ? -Math.abs(n) : n;
}

/**
 * Judge every publication date in a parsed file.
 *
 * @param {object[]} rows parsed rows, exactly as the loader has them
 * @param {object}   opts `{ dateColumn, amountColumn }`
 * @returns {{supported: boolean, reason?: string, days: object[],
 *            certified: object[], rowsDoubled: number, amountDoubled: number}}
 *
 * ⚠ Returns `supported: false` rather than a clean pass when it cannot judge.
 * A check that silently reports "no problem found" when it never looked is how
 * a gate becomes decoration.
 */
export function judgeDoubledExportDays(rows, { dateColumn, amountColumn } = {}) {
  if (!dateColumn) {
    return { supported: false, reason: 'no date_column in column_mapping, so rows cannot be grouped by publication date', days: [], certified: [], rowsDoubled: 0, amountDoubled: 0 };
  }
  if (!Array.isArray(rows) || rows.length === 0) {
    return { supported: true, days: [], certified: [], rowsDoubled: 0, amountDoubled: 0 };
  }

  const buckets = new Map();
  for (const r of rows) {
    const d = dayKey(r[dateColumn]);
    if (!buckets.has(d)) buckets.set(d, []);
    buckets.get(d).push(r);
  }

  // ⚠ Everything landing in one bucket means the date column did not parse as
  // dates. Judging that single bucket would compare a whole year against
  // thresholds meant for one day.
  if (buckets.size === 1 && rows.length > MIN_ROWS_TO_CERTIFY) {
    const only = [...buckets.keys()][0];
    if (!/^\d{4}-\d{2}-\d{2}$/.test(only)) {
      return { supported: false, reason: `every row has the same unparseable date bucket ${JSON.stringify(only)}`, days: [], certified: [], rowsDoubled: 0, amountDoubled: 0 };
    }
  }

  const days = [];
  for (const [date, sub] of buckets) {
    const counts = new Map();
    for (const r of sub) {
      const h = hashRow(r);
      counts.set(h, (counts.get(h) || 0) + 1);
    }
    const tally = [...counts.values()];
    const distinct = tally.length;
    const extra = sub.length - distinct;
    const evenShare = tally.filter((n) => n % 2 === 0).length / distinct;
    const onceShare = tally.filter((n) => n === 1).length / distinct;

    let amount = 0;
    if (amountColumn) {
      const seen = new Map();
      for (const r of sub) {
        const h = hashRow(r);
        const n = (seen.get(h) || 0) + 1;
        seen.set(h, n);
        if (n > 1) amount += parseAmountSafe(r[amountColumn]);
      }
    }

    // ⚠ No "has duplicates at all" precondition: a day with none has every
    // count at 1, which is odd, so evenShare is 0 and the first test refuses it.
    const shaped = evenShare >= MIN_EVEN_SHARE
      && sub.length / distinct <= MAX_MEAN_MULTIPLICITY;

    days.push({
      date,
      rows: sub.length,
      distinct,
      extra,
      evenShare,
      onceShare,
      amount: Math.round(amount * 100) / 100,
      shaped,
      big: shaped && sub.length >= MIN_ROWS_TO_CERTIFY,
      certified: false,
      spillover: false,
    });
  }

  const bigTimes = days.filter((d) => d.big).map((d) => Date.parse(d.date)).filter(Number.isFinite);
  for (const d of days) {
    if (d.big) { d.certified = true; continue; }
    if (!d.shaped) continue;
    const t = Date.parse(d.date);
    if (!Number.isFinite(t)) continue;
    if (bigTimes.some((b) => Math.abs(t - b) <= SPILLOVER_WINDOW_DAYS * 86400000)) {
      d.certified = true;
      d.spillover = true;
    }
  }

  days.sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));
  const certified = days.filter((d) => d.certified);
  return {
    supported: true,
    days,
    certified,
    rowsDoubled: certified.reduce((a, d) => a + d.extra, 0),
    amountDoubled: Math.round(certified.reduce((a, d) => a + d.amount, 0) * 100) / 100,
  };
}

/** One human line per certified day, for a loader refusal or a report. */
export function describeDoubledDays(verdict) {
  return verdict.certified.map((d) =>
    `${d.date}: ${d.rows.toLocaleString()} rows, ${d.distinct.toLocaleString()} distinct, ` +
    `${(d.evenShare * 100).toFixed(0)}% even, ${(d.onceShare * 100).toFixed(0)}% appear once, ` +
    `$${d.amount.toLocaleString(undefined, { minimumFractionDigits: 2 })} duplicated` +
    (d.spillover ? '  [small day inside the window]' : ''));
}
