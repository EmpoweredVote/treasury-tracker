/**
 * Grade one `data_source` string.
 *
 * Returns `{value: 'unknown', entryId: null}` for every failure path — no match,
 * no evidence, an illegal value, a throwing matcher, a null input. The
 * destructive direction here is "assert a grade", never "skip".
 *
 * @param {string|null|undefined} dataSource
 * @returns {{value: string, entryId: string|null}}
 */
export function gradeFor(dataSource, context = null) {
  const base = classifyAxis(dataSource, AUDIT_GRADE_REGISTRY, AUDIT_GRADE_VALUES, AUDIT_GRADE.UNKNOWN);
  if (base.entryId === null) return base;

  const entry = AUDIT_GRADE_REGISTRY.find((e) => e.id === base.entryId);
  if (typeof entry?.branch !== 'function') return base;

  // ⚠⚠ A BRANCHING ENTRY MAY ONLY MOVE THE GRADE ON EVIDENCE. `branch()` returns
  // null when it cannot resolve the entity-year, and the entry's own `value` —
  // the weaker branch — stands. There is no path here that grades a row higher
  // than the family's floor without the publisher's own classification saying so.
  const branched = entry.branch(context);
  if (branched == null) return base;
  if (!AUDIT_GRADE_VALUES.includes(branched) || branched === AUDIT_GRADE.UNKNOWN) return base;
  return { value: branched, entryId: base.entryId };
}
