/**
 * Per-(city, fiscal year) statutory class for Minnesota, read verbatim from the
 * publisher's own `ClassCode` column. Generated by
 * `scripts/buildMnOsaAuditBranch.mjs`; `--check` proves it still matches source.
 *
 * ⚠ readFileSync rather than a JSON import so this module stays loadable under
 * every runner in the repo without an import-attributes flag.
 */
const MN_OSA_BRANCH = JSON.parse(
  readFileSync(new URL('./mnOsaAuditBranch.json', import.meta.url), 'utf8'),
);

/** Fifth class IS "under 2,500 in population" — the OSA report states it. */
const MN_CLASS_NO_AUDIT_DUTY = 5;

/**
 * The audit grade for ONE Minnesota entity-year, or null when it cannot be shown.
 *
 * ⚠⚠ RETURNS null RATHER THAN GUESSING. An entity-year this cannot resolve falls
 * back to the entry's own `value`, which is deliberately the WEAKER branch — the
 * "mixed source takes the weaker branch" rule that already holds CA SCO and
 * Pennsylvania down. Nothing here can ever UPGRADE a row without evidence.
 */
export function mnOsaGradeFor(context) {
  if (!context) return null;
  const { entityType, name, fiscalYear } = context;

  // ⚠ Counties need no lookup: Minn. Stat. § 6.481 subd. 2 makes the annual audit
  // UNCONDITIONAL, so the class does not enter into it.
  if (entityType === 'county') return AUDIT_GRADE.COMPILED_FROM_AUDITED;
  if (entityType !== 'city') return null;

  const classCode = MN_OSA_BRANCH.cities?.[name]?.[String(fiscalYear)];
  if (!Number.isInteger(classCode)) return null;
  return classCode === MN_CLASS_NO_AUDIT_DUTY
    ? AUDIT_GRADE.SELF_REPORTED_UNAUDITED
    : AUDIT_GRADE.COMPILED_FROM_AUDITED;
}

