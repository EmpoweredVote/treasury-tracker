/**
 * The audit branch, recorded in the data_source string.
 *
 * ⚠ All three branches grade `self_reported_unaudited` — Chris's call,
 * 2026-08-29. Georgia DCA performs NO reconciliation to audited statements
 * (unlike FL DFS), and CVIOG states the figures "may or may not be audited
 * amounts". The branch is recorded anyway so it stays visible and re-gradable
 * later WITHOUT a reload, which is the whole reason it is in the source string.
 */
export function auditBranch(audited) {
  if (audited === true) return 'preparer-certified audited';
  if (audited === false) return 'self-reported';
  return 'audit status not stated';
}

export function sourceNameFor(datasetType, fiscalYear, audited) {
  const face = datasetType === 'operating' ? 'Expenditure by Function' : 'Revenue by Source';
  return `${SOURCE_PREFIX} — ${face} (FY${fiscalYear} actual, ${auditBranch(audited)})`;
}

/** Read one worksheet into a zero-indexed grid. */
function gridOf(wb, name) {
  const ws = wb.getWorksheet(name);
  if (!ws) return null;
  const rows = [];
  ws.eachRow({ includeEmpty: true }, (row, i) => {
    const arr = [];
    row.eachCell({ includeEmpty: true }, (cell, c) => { arr[c - 1] = cell.value; });
    rows[i - 1] = arr;
  });
  for (let i = 0; i < rows.length; i++) if (!rows[i]) rows[i] = [];
  return rows;
}

/**
 * Parse `{CICOID}_{FY}_RLGF_{Name}.xlsx`.
 *
 * ⚠ REFUSES A NON-NUMERIC YEAR. DCA's own listing serves
 * `2005001_YEAR_RLGF_Milledgeville.xls`, a literal placeholder. Coercing that
 * would mint a row under fiscal year NaN or 0.
 */
export function parseFilename(file) {
  const m = basename(file).match(/^(\d{7})_(\d{4})_RLGF_(.+)\.xlsx$/i);
  if (!m) return null;
  return { cicoid: m[1], fiscalYear: Number(m[2]), label: m[3] };
}

/** Nested `{n, a, c}` shape that `treasury_sync_city_budget` expects. */
function toTree(built) {
  return built.roots
    .filter((r) => r.items.length > 0 || r.amount !== 0)
    .map((r) => {
      const children = r.items
        .filter((i) => i.amount !== 0)
        .map((i) => ({ n: i.label, a: i.amount }));
      return children.length ? { n: r.label, a: r.amount, c: children } : { n: r.label, a: r.amount };
    });
}

/**
 * Resolve the fiscal-year start month, and say how.
 *
 * Two sources: the filing's OWN `FYEmonth` field, and the FAC census entry for
 * the entity. Never returns a month the two contradict, and never silently
 * defaults — `project_fysm_column_default_one_defect` is the story of a month
 * that defaulted rather than admitting ignorance.
 *
 * ⚠ Baldwin FY2020 prints the unfilled placeholder "MONTH", so the form yields
 * nothing and the registry value carries it. That is recorded, not hidden.
 */
export function resolveMonth(entity, meta, fiscalYear) {
  const fromForm = meta.fyEndMonth;
  // ⚠ A government that CHANGED its calendar inside the window carries the far
  // side's months per year. `treasury_sync_city_budget` already takes the month
  // per filing, so a change is representable in the data; only the registry was
  // single-valued. See GA_FYE_MONTH_CHANGES for the evidence behind each one.
  const declared = entity.monthByYear?.[fiscalYear] ?? entity.fiscalYearStartMonth;
  if (fromForm && fromForm !== declared) {
    // ⚠⚠ THE ONE WAY A DISAGREEING MONTH MAY STAND. A corroborated one-year
    // keying slip in the form, and ONLY where the registry pins BOTH the month
    // the form printed AND the month written instead. A slip of a different
    // size, year or entity matches nothing and still refuses — the same shape
    // as explainChecks() above, and for the same reason.
    const d = fyeMonthDefect(entity.cicoid, fiscalYear);
    if (d && d.formMonth === fromForm && d.month === declared) {
      return {
        month: declared,
        how: `form prints month ${fromForm} (${JSON.stringify(meta.fyEndMonthText)}); `
          + `corroborated one-year slip, writing ${declared} — ${d.id}`,
        ok: true,
        confirmed: false,
        defect: d,
      };
    }
    return { month: null, how: `CONFLICT form=${fromForm} registry=${declared}`, ok: false };
  }
  if (!fromForm) {
    return {
      month: declared,
      how: `registry only (form FYEmonth = ${JSON.stringify(meta.fyEndMonthText)})`,
      ok: true,
      confirmed: entity.censusConfirms,
    };
  }
  return {
    month: declared,
    how: entity.censusConfirms ? 'form + FAC census agree' : 'form only (census has no row)',
    ok: true,
    confirmed: entity.censusConfirms,
  };
}

/**
 * Mark the failing checks a corroborated registry entry accounts for.
 *
 * Mutates `checks`, setting `explainedBy` on each one it can account for, and
 * returns the entries used. Everything it does NOT mark still fails the load.
 *
 * ⚠⚠ ALL THREE FIGURES ARE PINNED — the form's total, the items' total and the
 * difference. Matching only the delta would let a registry entry excuse a
 * section whose numbers had both moved by the same amount, which is a different
 * filing, not the recorded defect.
 */
export function explainChecks(checks, cicoid, fiscalYear) {
  const explained = [];
  for (const c of checks) {
    if (c.ok || c.skipped || c.tag !== 'EXP') continue;
    const d = formTotalDefect(cicoid, fiscalYear, c.id);
    if (!d) continue;
    if (Math.abs(Number(c.expected) - d.formTotal) > 0.005) continue;
    if (Math.abs(Number(c.actual) - d.itemsTotal) > 0.005) continue;
    if (Math.abs(Number(c.actual) - Number(c.expected) - d.shortfall) > 0.005) continue;
    c.explainedBy = d;
    explained.push(d);
  }
  // The Part V grand total is a sum of the section totals, so it inherits every
  // section shortfall. It is explained ONLY if its own gap equals their SUM —
  // never on its own, and never by a gap no section accounted for. Without that
  // rule a single explained section would excuse any grand-total discrepancy.
  const grand = checks.find((c) => c.id === 'Part V grand');
  if (grand && !grand.ok && !grand.skipped && explained.length) {
    const shortfall = explained.reduce((a, d) => a + d.shortfall, 0);
    if (Math.abs(Number(grand.actual) - Number(grand.expected) - shortfall) <= 0.005) {
      grand.explainedBy = {
        id: 'inherited-from-sections',
        inheritedFrom: explained.map((d) => d.id),
        shortfall,
      };
    }
  }
  return explained;
}

/**
 * Does a recorded UNVERIFIABLE entry account for EXACTLY this filing's failure?
 *
 * ⚠⚠ PINNED BOTH WAYS. The entry must name every check that was skipped and
 * every check that failed, and the filing must produce exactly those sets —
 * no more, no fewer. A filing that breaks a second way alongside the recorded
 * one matches nothing and still refuses the whole run, so this register cannot
 * grow to cover problems nobody looked at. Same discipline as explainChecks().
 */
export function unverifiableMatches(entry, skippedChecks, badChecks) {
  if (!entry) return false;
  const same = (a, b) => a.length === b.length && [...a].sort().join('|') === [...b].sort().join('|');
  const skippedIds = skippedChecks.map((c) => `${c.tag} ${c.id}`);
  const badIds = badChecks.map((c) => `${c.tag} ${c.id}`);
  return same(skippedIds, entry.skipped) && same(badIds, entry.failed);
}

/** Parse one workbook fully, running every oracle. */
export async function readFiling(path) {
  const meta0 = parseFilename(path);
  if (!meta0) return { skipped: 'filename', path };
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(path);
  const load1 = gridOf(wb, 'LOAD1');
  // FY2009-2015 uses `Exportable Data` instead; a different key set, filed as a
  // follow-up. Reported as skipped, never counted as a pass.
  if (!load1) return { skipped: 'no LOAD1 (pre-FY2016 form)', ...meta0, path };

  const { blocks } = parseLoad1(load1);
  const pages = {};
  for (const n of Object.keys(PAGE_GEOMETRY)) {
    const g = gridOf(wb, n);
    if (g) pages[n] = g;
  }
  const { labels } = harvestLabels(pages);
  const { values: pageValues } = readPageValues(pages);
  aliasBareCodes(pageValues, new Set(Object.values(blocks).flatMap((b) => Object.keys(b))));

  const anomalies = [];
  const exp = buildExpenditureTree(blocks, labels, pageValues, anomalies);
  const rev = buildRevenueTree(blocks, labels, pages, pageValues, anomalies);
  const log1 = readLog1(blocks._LOG1 || {});

  const checks = [
    ...checkSectionTotals(exp, blocks, EXPENDITURE_SECTIONS).map((c) => ({ ...c, tag: 'EXP' })),
    ...checkSectionTotals(rev, blocks, REVENUE_SECTIONS).map((c) => ({ ...c, tag: 'REV' })),
    ...checkPartTotals(rev, blocks).map((c) => ({ ...c, tag: 'REV' })),
  ];
  const grandExpected = OBJECT_COLUMNS.reduce((a, o) => a + num((blocks._E6 || {})[`TTL_PART5_${o}`]), 0);
  checks.push({
    tag: 'EXP', id: 'Part V grand', expected: grandExpected, actual: exp.total,
    ok: Math.abs(grandExpected - exp.total) <= 0.005,
  });

  // ── ⚠⚠ THE ONE WAY A FAILING CHECK MAY STAND ─────────────────────────────
  //
  // A section whose printed total contradicts its own printed line items is a
  // KNOWN, CORROBORATED defect in the publisher's workbook, not a parse error —
  // but only where GA_FORM_TOTAL_DEFECTS says so, and only where the registry's
  // recorded numbers match the ones measured here TO THE CENT. All three are
  // pinned: the form's total, the items' total, and the difference between them.
  //
  // ⚠ This deliberately cannot absorb a NEW problem. A defect of a different
  // size, in a different section, in a different year, or on a different entity
  // matches nothing and still refuses the filing. The registry entry is the
  // evidence; this code is only the lookup.
  explainChecks(checks, meta0.cicoid, meta0.fiscalYear);

  return { ...meta0, path, exp, rev, log1, checks, anomalies };
}

async function main() {
  const { values: argv } = parseArgs({
    options: {
      dir: { type: 'string' },
      entity: { type: 'string' },
      fy: { type: 'string' },
      commit: { type: 'boolean' },
      'dry-run': { type: 'boolean' },
    },
    strict: false,
  });
  const dir = argv.dir || '_acfr-work/ga/xlsx';
  const commit = !!argv.commit && !argv['dry-run'];

  const files = readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.xlsx')).sort();
  const wanted = new Set(
    argv.entity
      ? GA_ALL_ENTITIES.filter((e) => e.key === argv.entity).map((e) => e.cicoid)
      : GA_ALL_ENTITIES.map((e) => e.cicoid),
  );
  if (argv.entity && wanted.size === 0) {
    console.error(`Unknown --entity ${argv.entity}`);
    process.exit(2);
  }

  const filings = [];
  const skipped = [];
  for (const f of files) {
    const parsed = parseFilename(f);
    if (!parsed) { skipped.push(`${f}: unparseable filename`); continue; }
    if (!wanted.has(parsed.cicoid)) continue;
    if (argv.fy && parsed.fiscalYear !== Number(argv.fy)) continue;
    if (parsed.fiscalYear < GA_LOAD_WINDOW.firstFiscalYear
      || parsed.fiscalYear > GA_LOAD_WINDOW.lastFiscalYear) {
      skipped.push(`${f}: FY outside the ${GA_LOAD_WINDOW.firstFiscalYear}-${GA_LOAD_WINDOW.lastFiscalYear} window`);
      continue;
    }
    const filing = await readFiling(join(dir, f));
    if (filing.skipped) { skipped.push(`${f}: ${filing.skipped}`); continue; }
    filings.push(filing);
  }

  // ⚠⚠ A GATE THAT CAN MEASURE NOTHING MUST FAIL, NOT PASS. Session 3 shipped a
  // parse that produced zero rows, counted zero checks, and printed "Oracle
  // green". Refuse an empty run outright.
  if (filings.length === 0) {
    console.error('REFUSING: no filings parsed. Nothing was measured, so nothing is verified.');
    process.exit(1);
  }

  let failed = 0;
  let checksRun = 0;
  const anomalies = [];
  const excluded = [];
  console.log(`${'entity'.padEnd(20)} ${'FY'.padEnd(5)} ${'operating'.padStart(16)} ${'revenue'.padStart(18)} mo  audited  oracle`);
  for (const f of filings) {
    const ent = entityByCicoid(f.cicoid);
    const m = resolveMonth(ent, f.log1, f.fiscalYear);
    // ⚠ `explainedBy` is set ONLY by a corroborated GA_FORM_TOTAL_DEFECTS entry
    // that pinned every figure. It is excluded from `bad` but printed below, so
    // it can never pass silently.
    const bad = f.checks.filter((c) => !c.ok && !c.skipped && !c.explainedBy);
    const explainedChecks = f.checks.filter((c) => c.explainedBy);
    const skippedChecks = f.checks.filter((c) => c.skipped);
    checksRun += f.checks.length - skippedChecks.length;
    // ⚠⚠ A filing whose own printed subtotals are #REF! cannot be checked at
    // all. It is EXCLUDED from the load rather than published unverified —
    // "looks plausible beside its neighbours" is not a measurement. The entry
    // must account for exactly this failure or the run still refuses.
    const unver = unverifiableFiling(f.cicoid, f.fiscalYear);
    if (unverifiableMatches(unver, skippedChecks, bad)) {
      f.excluded = unver;
      excluded.push(unver);
      console.log(`${ent.name.padEnd(20)} ${String(f.fiscalYear).padEnd(5)} `
        + `EXCLUDED, NOT LOADED — oracle cannot run: ${unver.id}`);
      continue;
    }
    if (bad.length || skippedChecks.length || !m.ok) failed++;
    for (const a of f.anomalies) anomalies.push({ entity: ent.key, fiscalYear: f.fiscalYear, ...a });
    console.log(
      `${ent.name.padEnd(20)} ${String(f.fiscalYear).padEnd(5)} `
      + `${f.exp.total.toLocaleString().padStart(16)} ${f.rev.total.toLocaleString().padStart(18)} `
      + `${String(m.month ?? '??').padEnd(3)} ${auditBranch(f.log1.audited).padEnd(28)} `
      + `${f.checks.length - bad.length - skippedChecks.length}/${f.checks.length}`,
    );
    for (const c of bad) {
      console.log(`      ✗ ${c.tag} ${c.id}: form ${Number(c.expected).toLocaleString()} vs tree ${Number(c.actual).toLocaleString()}`);
    }
    for (const c of skippedChecks) console.log(`      ? ${c.tag} ${c.id}: SKIPPED ${c.reason || ''}`);
    for (const c of explainedChecks) {
      console.log(
        `      ⚠ ${c.tag} ${c.id}: the PUBLISHER'S OWN total contradicts its own line items — `
        + `form ${Number(c.expected).toLocaleString()} vs items ${Number(c.actual).toLocaleString()} `
        + `(short ${Number(c.explainedBy.shortfall).toLocaleString()}). Loading the items. [${c.explainedBy.id}]`,
      );
    }
    if (!m.ok) console.log(`      ✗ fiscal month: ${m.how}`);
  }

  console.log(`\n${filings.length} filings · ${checksRun} oracle checks run · ${failed} filing(s) with a failure`);
  if (skipped.length) {
    console.log(`\nSkipped (${skipped.length}) — reported, never silently dropped:`);
    for (const s of skipped) console.log(`   ${s}`);
  }
  if (anomalies.length) {
    console.log(`\n⚠ ANOMALIES — the publisher's extract disagrees with its own printed form (${anomalies.length}).`);
    console.log('  The printed form is loaded; these are recorded, not suppressed. See the Milledgeville Rule.');
    for (const a of anomalies) {
      // ⚠ `extract` is null when the publisher's cell is an Excel error — a
      // different fact from "the extract says zero", and the reason this prints
      // #REF! rather than a number.
      const extract = a.extract === null ? '#REF! (no value)' : a.extract.toLocaleString();
      console.log(`   ${a.entity} FY${a.fiscalYear} ${a.section} ${a.code} "${a.label}": form ${a.form.toLocaleString()} vs extract ${extract}`);
    }
  }

  if (failed) {
    console.error(`\nREFUSING TO WRITE: ${failed} filing(s) did not reconcile to the publisher's own printed subtotals.`);
    console.error('A tree that does not tie means the document was not read correctly — that is a read-fidelity');
    console.error('failure, NOT a judgement about whether the figures look right.');
    process.exit(1);
  }

  if (!commit) {
    console.log('\nDRY RUN — nothing written. Pass --commit to write.');
    return;
  }

  const url = process.env.SUPABASE_URL || 'https://kxsdzaojfaibhuzmclfq.supabase.co';
  const key = process.env.SUPABASE_SERVICE_KEY || process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!key) { console.error('Missing SUPABASE_SERVICE_KEY'); process.exit(1); }
  const db = createClient(url, key);

  // ⚠ ONLY the entities this run actually parsed a filing for. Creating a
  // municipality per REGISTRY row was harmless at 7 entities and is not at 146:
  // it would mint a TT city for every government in the registry, including ones
  // whose every filing was refused upstream — a government that exists in TT
  // with no figures at all, created as a side effect of a load that wrote
  // nothing for it.
  // ⚠ Excluded filings never reach the write loop, and never contribute an
  // entity to it either.
  const writable = filings.filter((f) => !f.excluded);
  const loading = new Set(writable.map((f) => f.cicoid));
  const involved = GA_ALL_ENTITIES.filter((e) => loading.has(e.cicoid));
  // Counties first: a city's county_id must exist before the city is created.
  const order = [...involved].sort((a, b) => (a.parentCountyKey ? 1 : 0) - (b.parentCountyKey ? 1 : 0));
  const ids = new Map();
  for (const ent of order) {
    const { id: data } = await ensureMunicipality(db, {
      name: ent.name, state: GA_STATE, entityType: ent.entityType, population: ent.population,
    });
    ids.set(ent.key, data);
    console.log(`  entity ${ent.name} -> ${data}`);
  }
  for (const ent of involved) {
    if (!ent.parentCountyKey) continue;
    const { error } = await db.schema('treasury').from('municipalities')
      .update({ county_id: ids.get(ent.parentCountyKey) }).eq('id', ids.get(ent.key));
    if (error) throw new Error(`county_id error (${ent.name}): ${error.message}`);
  }

  const sourceDate = new Date().toISOString().slice(0, 10);
  let written = 0;
  let conflicts = 0;
  const emptied = [];
  let categories = 0;
  for (const f of writable) {
    const ent = entityByCicoid(f.cicoid);
    const municipalityId = ids.get(ent.key);
    const m = resolveMonth(ent, f.log1, f.fiscalYear);
    for (const [datasetType, built] of [['operating', f.exp], ['revenue', f.rev]]) {
      const tree = toTree(built);
      // ⚠⚠ NEVER WRITE AN EMPTY TREE. Every section of this Part is $0.00, so
      // the form's own printed totals are $0.00 too and all eighteen checks tie
      // AT ZERO — the oracle reports 18/18 having measured nothing. A row with
      // no categories renders as an empty page while telling a reader the
      // government's spending was nothing. The preparer left the Part blank;
      // that is missing data, and missing data gets no row.
      // ⚠ Not an exception to the Milledgeville Rule: that rule is about
      // FIGURES that look wrong, which load and are flagged. There is no figure
      // here. The other dataset in the same filing still loads.
      if (tree.length === 0) {
        const rec = emptyDataset(f.cicoid, f.fiscalYear, datasetType);
        if (!rec) {
          throw new Error(`${ent.name} FY${f.fiscalYear} ${datasetType}: the tree is EMPTY and no `
            + 'GA_EMPTY_DATASETS entry records it. A new blank Part must be looked at, not skipped.');
        }
        emptied.push(rec);
        console.log(`  SKIP ${ent.name} FY${f.fiscalYear} ${datasetType} — the publisher left this `
          + `Part blank (every section $0.00); no row written [${rec.id}]`);
        continue;
      }
      // Never-overwrite guard: `treasury_sync_city_budget` is NOT source-safe —
      // it never updates data_source, so it would overwrite another publisher's
      // row or silently insert a duplicate.
      const { data: existing, error: lookupErr } = await db
        .schema('treasury').from('budgets')
        .select('id, data_source')
        .eq('municipality_id', municipalityId)
        .eq('fiscal_year', f.fiscalYear)
        .eq('dataset_type', datasetType)
        .limit(1);
      if (lookupErr) throw new Error(`Budget lookup failed: ${lookupErr.message}`);
      if (existing?.[0] && !String(existing[0].data_source || '').startsWith(SOURCE_PREFIX)) {
        conflicts++;
        console.log(`  SKIP ${ent.name} FY${f.fiscalYear} ${datasetType} — "${existing[0].data_source}" preserved`);
        continue;
      }
      const { data, error } = await db.rpc('treasury_sync_city_budget', {
        p_municipality_id: municipalityId,
        p_fiscal_year: f.fiscalYear,
        p_dataset_type: datasetType,
        p_total: built.total,
        p_tree: tree,
        p_row_count: tree.length,
        p_data_source_name: sourceNameFor(datasetType, f.fiscalYear, f.log1.audited),
        p_source_url: SOURCE_URL,
        p_source_date: sourceDate,
        p_fiscal_year_start_month: m.month,
        // ⚠⚠ LOAD-BEARING, not decoration. The RPC keys on (municipality,
        // fiscal_year, dataset_type, fund_scope, basis). Omit them and BOTH
        // default to 'unknown', so a re-run after the stampers have run matches
        // nothing and takes the INSERT branch — silently duplicating every row.
        p_fund_scope: FUND_SCOPE,
        p_basis: BASIS_VALUE,
        p_derivation: DERIVATION,
      });
      // ⚠⚠ THE RPC REPORTS FAILURE IN ITS RETURN PAYLOAD, NOT AS A POSTGREST
      // ERROR. treasury_sync_city_budget ends with
      //     EXCEPTION WHEN OTHERS THEN RETURN jsonb_build_object('error', SQLERRM);
      // so a constraint violation comes back as `data.error` while `error` is
      // null and the call looks like a success. Checking only `error` made this
      // loader report "Wrote 76 budget rows" while writing NOTHING AT ALL — the
      // exact shape of session 3's zero-row parse that printed "Oracle green".
      // A write that cannot prove it wrote must fail.
      if (error) throw new Error(`RPC transport error (${ent.name} FY${f.fiscalYear} ${datasetType}): ${error.message}`);
      if (data?.error) throw new Error(`RPC refused (${ent.name} FY${f.fiscalYear} ${datasetType}): ${data.error}`);
      if (data?.status !== 'success' || !data?.budget_id) {
        throw new Error(`RPC returned no success status (${ent.name} FY${f.fiscalYear} ${datasetType}): ${JSON.stringify(data)}`);
      }
      written++;
      categories += tree.reduce((a, r) => a + 1 + (r.c?.length || 0), 0);
    }
  }
  console.log(`\nWrote ${written} budget rows over ${categories.toLocaleString()} categories `
    + `(${conflicts} skipped by the never-overwrite guard).`);
  // ⚠⚠ A RUN THAT WROTE NOTHING MUST NOT READ AS A SUCCESS. This loader once
  // printed "Wrote 76 budget rows" having written none at all — every RPC call
  // had been refused by a check constraint and reported it in its RETURN
  // PAYLOAD rather than as a transport error. Counting ATTEMPTS is not counting
  // WRITES. The proof of a write is the `budget_id` the RPC returns, asserted
  // per call above.
  //
  // ⚠ Do NOT gate on the RPC's `rows_inserted`: it counts third-level
  // `budget_line_items`, and this tree is TWO levels (section -> line, both
  // categories), so it is legitimately 0 on every call. Gating on it refuses a
  // perfectly good load — measured, not reasoned about.
  if (written === 0 || categories === 0) {
    console.error('REFUSING: no rows were actually written. Nothing was measured, so nothing is verified.');
    process.exit(1);
  }
  console.log('Now run:  npm run verify:frozen');
  console.log('     then npm run check:forks           # no publisher rename forked a city');
  console.log('     then npm run register:rows -- --milestone knight-s4-georgia --match "Georgia DCA Report of Local Government Finances"');
  console.log('     then node scripts/syncFrozenInvariantState.mjs   # mirror the exclusions into the DB');
}

