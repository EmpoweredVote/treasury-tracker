/**
 * Every Georgia government this loader can write, from both registries.
 *
 * `georgiaRlgfEntities.mjs` is the 7 hand-written wave-1/wave-2 governments;
 * `georgiaStatewideEntities.mjs` is GENERATED by buildGaStatewideEntities.mjs.
 *
 * ⚠⚠ THE OVERLAP ASSERTION IS LOAD-BEARING. `treasury_sync_city_budget` keys on
 * (municipality, fiscal_year, dataset_type, fund_scope, basis) and is NOT
 * source-safe, so two registry entries claiming one CICOID under two different
 * keys would mint a second municipality and DUPLICATE every row of that
 * government rather than collide visibly
 * (`project_sync_city_budget_not_source_safe`). The generated registry already
 * excludes the hand-written seven; this proves it at import time rather than
 * trusting it.
 */
export const GA_ALL_ENTITIES = Object.freeze([...GA_RLGF_ENTITIES, ...GA_STATEWIDE_ENTITIES]);

const seenCicoids = new Set();
const seenKeys = new Set();
for (const e of GA_ALL_ENTITIES) {
  if (seenCicoids.has(e.cicoid)) throw new Error(`two registry entries claim CICOID ${e.cicoid} (${e.name})`);
  if (seenKeys.has(e.key)) throw new Error(`two registry entries claim key ${JSON.stringify(e.key)} (${e.name})`);
  seenCicoids.add(e.cicoid);
  seenKeys.add(e.key);
}

/** Look one up by CICOID — the only safe key, across both registries. */
export function entityByCicoid(cicoid) {
  return GA_ALL_ENTITIES.find((e) => e.cicoid === String(cicoid)) || null;
}

