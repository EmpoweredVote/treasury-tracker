/**
 * ⚠⚠ EVERY AUTHOR-FACING REGISTER, NOT JUST GEORGIA'S.
 *
 * These guards were written when GA was the only register, and they asserted
 * that every reader-facing flag traces to `GA_FIGURE_FLAGS`. That stopped
 * being the right assertion the moment a second register existed: the first
 * non-Georgia flag would have failed as "an id the register does not carry"
 * even though its register entry was sitting right there.
 *
 * ⚠ ADD EVERY NEW REGISTER HERE. A register that is not in this list cannot
 * surface a flag — and worse, the test that proves corroborated findings reach
 * readers would silently stop covering it.
 *
 * ⚠⚠ scripts/data/friscoRegisterAnomalies.mjs is DELIBERATELY ABSENT. It is
 * marked not-reader-facing: its claim is an inference about the publisher
 * ("therefore the day was exported twice"), not a fact about the file, and it
 * has not been independently corroborated. Adding it here would be promoting
 * it by the back door.
 */
const AUTHOR_FACING_REGISTERS = [
  ...GA_FIGURE_FLAGS,
  ...MCKINNEY_REGISTER_ANOMALIES,
  ...OUT_OF_PERIOD_EXCEPTIONS,
  // ⭐⭐ THE FIRST REGISTER NOBODY WROTE BY HAND. Generated by
  // scripts/generateBondFinancedRevenue.mjs from the State Controller's own
  // figures, so its entries carry `loaded`/`readerFacing` by construction — a
  // year is in it only because it crossed the published threshold. The guards
  // below treat it exactly like the authored registers, which is the point:
  // a rule-emitted flag earns its place on the page the same way.
  ...BOND_FINANCED_YEARS,
  // ⭐⭐⭐ THE TWO REGISTERS THAT REPLACED SIX HAND-WRITTEN ENTRIES. West
  // Hollywood's five straddle banners and McKinney's eleven-month banner are
  // now measured over every transactions budget rather than over the cities
  // somebody visited — and the same question found Frisco FY2021, a ten-month
  // year nobody had ever flagged.
  //
  // ⚠⚠ A REGISTER THAT IS NOT IN THIS LIST CANNOT SURFACE A FLAG, and the
  // guard proving corroborated findings reach readers silently stops covering
  // it. That is the latent bug #362 found; adding a register here is not
  // optional bookkeeping.
  ...FISCAL_PERIOD_DISTORTION_YEARS,
  ...ABSENT_MONTH_YEARS,
];

/**
 * ⚠⚠ WHICH ENTRIES ARE *SUPPOSED* TO REACH A READER.
 *
 * `loaded` means the DATA is loaded — true of every out-of-period entry, since
 * the whole point of that registry is that TT keeps the publisher's rows. It
 * does NOT mean the finding is worth a banner. West Hollywood FY2023 is 2.4%
 * out of period; a banner there costs a reader attention and teaches them to
 * skip the FY2024 one that matters.
 *
 * So promotion is explicit: `readerFacing === true`, or a GA entry's `loaded`,
 * which has always carried both meanings for that register.
 */
const shouldSurface = (f) => f.readerFacing === true
  || (f.readerFacing === undefined && f.loaded === true);

/**
 * ⚠ TWO REGISTERS SPELL "LOADED" DIFFERENTLY, and both spellings are honest.
 * GA uses a `loaded` boolean; the out-of-period registry states it as
 * `disposition: 'loaded-as-published'` / `'loaded-below-publisher-total'`,
 * which is more precise about HOW it was loaded. The guard below only needs to
 * know that TT holds the figure, so it accepts either.
 */
const isLoaded = (f) => f?.loaded === true || String(f?.disposition ?? '').startsWith('loaded');

/**
 * ⚠⚠ THE GUARD THAT MATTERS: the author-facing register and the reader-facing
 * one must not drift. Every flag TT records about a government's figures was
 * invisible to readers until `src/data/figureFlags.ts` shipped, because nothing
 * under src/ read the register. These tests exist so that cannot happen again
 * silently — a new corroborated flag that is never surfaced now fails CI.
 */
describe('figure flags — reader-facing surfacing', () => {
  it('⚠⚠ every corroborated, loaded flag reaches the page — in EVERY register', () => {
    // ⚠ Was GA-only. A second register would otherwise have been able to
    // record a corroborated finding and never show it, which is the exact
    // failure this whole file was written to make impossible.
    const surfaced = new Set(Object.values(figureFlags).map((f) => f.id));
    const missing = AUTHOR_FACING_REGISTERS
      .filter(shouldSurface)
      .map((f) => f.id)
      .filter((id) => !surfaced.has(id));
    expect(missing, `recorded for maintainers but never shown to readers: ${missing.join(', ')}`)
      .toEqual([]);
  });

  /**
   * ⚠⚠⚠ A FLAG ABOUT A PERIOD MUST CARRY ITS OWN RETIREMENT CONDITION.
   *
   * McKinney's FY2026 banner says the year covers eleven months. If the city
   * republishes the file with September in it and TT reloads, that sentence
   * becomes FALSE — and a banner telling a reader a complete year is
   * incomplete is its own misinformation. The register entry has to say, in
   * mechanical terms, when to take it down.
   */
  it('⚠⚠ a period flag says when it must be retired', () => {
    const periodFlags = AUTHOR_FACING_REGISTERS.filter((f) => f.severity === 'incomplete-period');
    expect(periodFlags.length).toBeGreaterThan(0);
    for (const f of periodFlags) {
      expect(f.retireWhen, `${f.id} has no retirement condition`).toBeTruthy();
      expect(String(f.retireWhen).length, f.id).toBeGreaterThan(40);
    }
  });

  it('⚠ no reader-facing flag invents an id the register does not carry', () => {
    const known = new Set(AUTHOR_FACING_REGISTERS.map((f) => f.id));
    for (const f of Object.values(figureFlags)) {
      // Every surfaced flag must trace to a corroborated register entry — a
      // claim about a government's figures is never authored only in the UI.
      expect(known.has(f.id), `${f.id} has no entry in the author-facing register`).toBe(true);
    }
  });

  it('⚠ the register entry behind every surfaced flag is LOADED, never suppressed', () => {
    // The Milledgeville Rule: a flagged figure is published, not withheld. A
    // flag on a figure TT declined to load would be describing an absence.
    const byId = new Map(AUTHOR_FACING_REGISTERS.map((f) => [f.id, f]));
    for (const f of Object.values(figureFlags)) {
      expect(isLoaded(byId.get(f.id)), `${f.id} is flagged but its register entry is not loaded`).toBe(true);
    }
  });

  it('keys parse into entity|state|year|dataset, and the lookup honours all four', () => {
    for (const key of Object.keys(figureFlags)) {
      const parts = key.split('|');
      expect(parts).toHaveLength(4);
      expect(Number.isInteger(Number(parts[2]))).toBe(true);
      expect(['operating', 'revenue', 'salaries', 'transactions']).toContain(parts[3]);
    }
    expect(figureFlagFor('DeKalb County', 'GA', 2018, 'operating')).toBeTruthy();
    // ⚠ The exact four values App.tsx passes for McKinney's payments view.
    // `treasury.municipalities` holds name 'McKinney', state 'TX'; a flag
    // keyed on anything else renders NOTHING and fails silently.
    expect(figureFlagFor('McKinney', 'TX', 2026, 'transactions')).toBeTruthy();
    expect(figureFlagFor('McKinney', 'TX', 2025, 'transactions')).toBeUndefined();
    expect(figureFlagFor('McKinney', 'TX', 2026, 'operating')).toBeUndefined();
    // ⚠ A near-miss must NOT match: wrong year, wrong dataset, wrong state.
    expect(figureFlagFor('DeKalb County', 'GA', 2019, 'operating')).toBeUndefined();
    expect(figureFlagFor('DeKalb County', 'GA', 2018, 'revenue')).toBeUndefined();
    expect(figureFlagFor('DeKalb County', 'NC', 2018, 'operating')).toBeUndefined();
    expect(figureFlagFor(undefined, 'GA', 2018, 'operating')).toBeUndefined();
  });

  it('⚠ every flag carries reader-facing copy and at least one source', () => {
    for (const [key, f] of Object.entries(figureFlags)) {
      expect(f.headline.length, key).toBeGreaterThan(10);
      expect(f.summary.length, key).toBeGreaterThan(40);
      expect(f.entries.length, key).toBeGreaterThanOrEqual(1);
      for (const e of f.entries) {
        // Always-sourced ground rule — no unsourced prose ships to a reader.
        expect(e.source_name, key).toBeTruthy();
        expect(e.source_url, key).toMatch(/^https:\/\//);
        expect(e.source_date, key).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      }
    }
  });

  it('⚠⚠ the copy never implies wrongdoing', () => {
    // These are self-reported forms the publisher does not certify, and every
    // defect found so far UNDERSTATES spending. Tone is load-bearing: a flag
    // that reads as an accusation is a liability, not transparency.
    const forbidden = /\b(fraud|fraudulent|embezzl|corrupt|misappropriat|cover.?up|deliberate|falsif)/i;
    for (const [key, f] of Object.entries(figureFlags)) {
      const prose = [f.headline, f.summary, ...f.entries.flatMap((e) => [e.title ?? '', e.text])].join(' ');
      expect(forbidden.test(prose), `${key} uses accusatory language`).toBe(false);
    }
  });

  it('⚠⚠ a not-comparable flag never claims the figure is wrong', () => {
    // These figures are CORRECT — only the year-over-year comparison breaks.
    // Copy that implies a defect would tell the reader something false AND
    // impute a fault to a government that has none.
    const wrongness = /\b(understated|overstated|missing|incorrect|wrong|error|defect|should be)\b/i;
    for (const [key, f] of Object.entries(figureFlags)) {
      if (f.severity !== 'not-comparable') continue;
      expect(wrongness.test(f.headline), `${key} headline implies the figure is wrong`).toBe(false);
      // It must instead say what IS true: the comparison is the problem.
      const prose = `${f.headline} ${f.summary}`;
      expect(/not comparable|comparing|comparison|not a real/i.test(prose), key).toBe(true);
    }
  });

  it('⚠ both sides of a two-year seam are flagged, not just one', () => {
    // A reader can land on either year. Flagging only the odd-looking one
    // leaves the other silently misleading.
    const seam = Object.entries(figureFlags)
      .filter(([, f]) => f.id === 'fulton-fy2017-fy2018-property-tax-timing')
      .map(([k]) => k);
    expect(seam.sort()).toEqual([
      'Fulton County|GA|2017|revenue',
      'Fulton County|GA|2018|revenue',
    ]);
  });

  /**
   * ⚠⚠ WEST HOLLYWOOD HAS TWO SEAMS, and the receiving side of each is the
   * one that reads wrong without a banner: FY2025 shows $132.28M against
   * FY2024's $249.36M and looks like spending halved. Flagging only the
   * odd-looking side leaves the other silently misleading.
   */
  it('⚠⚠ both sides of each West Hollywood seam are flagged', () => {
    for (const [giving, receiving] of [[2019, 2020], [2024, 2025]]) {
      expect(figureFlagFor('West Hollywood', 'CA', giving, 'transactions'), `FY${giving}`)
        .toBeTruthy();
      expect(figureFlagFor('West Hollywood', 'CA', receiving, 'transactions'), `FY${receiving}`)
        .toBeTruthy();
    }
    // ⚠ And the years whose skew is too small for a banner stay unflagged, or
    // the ones that matter stop standing out.
    for (const quiet of [2018, 2021, 2022, 2023]) {
      expect(figureFlagFor('West Hollywood', 'CA', quiet, 'transactions'), `FY${quiet}`)
        .toBeUndefined();
    }
  });

  /**
   * ⚠⚠⚠ A FIGURE THAT IS STILL GROWING MUST BE DATED ON THE PAGE.
   *
   * West Hollywood's FY2025-26 register is sync_frequency WEEKLY and the city
   * is still posting into it, so the total this page prints for FY2026 rises on
   * its own. The first version of that banner said "$275.28 million shown here"
   * and "25.0%" flat — within weeks it would have been contradicted by the
   * figure displayed beside it, and would have UNDERSTATED the distortion it
   * exists to describe. A banner that disagrees with its own page is worse than
   * no banner.
   *
   * So any register entry marked `stillGrowing` must have reader-facing copy
   * that pins its numbers to a date, and must say the numbers move.
   */
  it('⚠⚠ a still-growing figure states its numbers as of a date', () => {
    const growing = AUTHOR_FACING_REGISTERS.filter((f) => f.stillGrowing === true && shouldSurface(f));
    expect(growing.length, 'no still-growing entry is surfaced — has the registry changed?')
      .toBeGreaterThan(0);

    const surfacedById = new Map(Object.values(figureFlags).map((f) => [f.id, f]));
    for (const entry of growing) {
      const f = surfacedById.get(entry.id);
      expect(f, `${entry.id} is marked stillGrowing but is not surfaced`).toBeTruthy();

      // ⚠ "as of <date>" has to be in the ALWAYS-VISIBLE copy, not only in the
      // evidence a reader must open. A skimming reader is exactly who misreads
      // a stale number.
      const visible = `${f.headline} ${f.summary}`;
      expect(/\bas of\b/i.test(visible), `${entry.id} quotes figures with no "as of" date`).toBe(true);
      expect(/\d{1,2} \w+ \d{4}|\d{4}-\d{2}-\d{2}/.test(visible), `${entry.id} has no explicit date`)
        .toBe(true);

      // ⚠ And it must tell the reader the number moves, or "as of" reads as
      // precision rather than as a warning.
      expect(
        /grow|rise|rising|keeps? (growing|rising)|still (posting|adding)|each week/i.test(visible),
        `${entry.id} does not say the figure moves`,
      ).toBe(true);
    }
  });

  it('⚠ states plainly that the figure is shown as filed', () => {
    // The reader must be able to tell that TT did not alter the number — that
    // is the whole difference between flagging and quietly correcting.
    for (const [key, f] of Object.entries(figureFlags)) {
      const prose = `${f.summary} ${f.entries.map((e) => e.text).join(' ')}`;
      expect(/as filed|as published|shown as|displayed exactly|genuinely what/i.test(prose), key).toBe(true);
    }
  });

  it('\u26a0\u26a0 no HEADLINE renders a verdict on the government', () => {
    // CONTEXT, NOT A VERDICT (Chris, 2026-10-17). A headline says what the
    // figure covers and what it leaves out. It does not pronounce the number
    // broken -- TT is not the auditor, and the Fulton FY2017 case showed a
    // figure can look broken and be a court-ordered delay.
    const verdict = /\b(wrong|incorrect|error|erroneous|broken|invalid|bogus|failed|failure|bad data|mistake)\b/i;
    for (const [key, f] of Object.entries(figureFlags)) {
      expect(verdict.test(f.headline), `${key} headline delivers a verdict`).toBe(false);
    }
  });

  it('\u26a0 every flag tells the reader what to DO with the figure', () => {
    // This replaced the implied verdict. A banner that only says "be wary"
    // leaves the reader with nothing actionable.
    for (const [key, f] of Object.entries(figureFlags)) {
      expect(f.whatThisMeans, key).toBeTruthy();
      expect(f.whatThisMeans.length, key).toBeGreaterThan(25);
      expect(f.whatThisMeans, key).not.toBe(f.summary);
    }
  });

  it('\u26a0\u26a0 the MAGNITUDE survives in the headline, since styling no longer carries it', () => {
    // Calm is not quiet. With one neutral treatment for every severity, the
    // only thing stopping a skimming reader misusing a figure that is out by
    // sevenfold is the number itself, stated up front.
    for (const [key, f] of Object.entries(figureFlags)) {
      const hasScale = /\d/.test(f.headline)
        || /\b(seven|half|most|almost none|none|all)\b/i.test(f.headline);
      expect(hasScale, `${key} headline states no magnitude`).toBe(true);
    }
  });
});

/**
 * ⭐⭐⭐ FLAGS THAT ARE RULES, NOT ENTRIES.
 *
 * Every other flag in this file exists because a person spent a day on that
 * entity, so "unflagged" has only ever meant "nobody looked". West Hollywood
 * FY2016 is the proof: its revenue reads $114.7M → $214.4M → $132.6M, the spike
 * is $85,015,000 of bond proceeds, and nothing flagged it — on one of the most
 * heavily examined entities in this repo.
 *
 * These guards fix what a rule may do, because a rule writes copy for dozens of
 * governments at once and nobody reads every sentence it produces.
 */
describe('rule-emitted flags', () => {
  const emitted = bondFinancedRevenueFlags();

  it('covers the whole series, not the entities somebody visited', () => {
    expect(BOND_FINANCED_YEARS.length).toBeGreaterThan(40);
    const entities = new Set(BOND_FINANCED_YEARS.map((r) => `${r.entity}|${r.state}`));
    expect(entities.size).toBeGreaterThan(30);
    // The year that started it, and the fact that it is NOT exceptional.
    expect(emitted['West Hollywood|CA|2016|revenue']).toBeTruthy();
    expect(entities.has('West Hollywood|CA')).toBe(true);
  });

  it('⚠⚠ emits no key a hand-written flag already owns', () => {
    // Hand-written wins in the merge, so a collision would silently drop the
    // rule's flag — or, if the order ever flipped, silently replace an authored
    // one. Either way a reader loses a sentence somebody wrote on purpose.
    const authored = new Set(
      Object.keys(figureFlags).filter((k) => !(k in emitted)),
    );
    const collisions = Object.keys(emitted).filter((k) => authored.has(k));
    expect(collisions, `rule and author both claim: ${collisions.join(', ')}`).toEqual([]);
  });

  it('⚠⚠⚠ states no figure that is not measured', () => {
    // THE defect this architecture exists to prevent (PR #364): a banner that
    // hard-codes a number drifts from the chart beside it. Every money figure
    // in the prose must appear in the row it came from.
    for (const row of BOND_FINANCED_YEARS) {
      const f = emitted[`${row.entity}|${row.state}|${row.fiscalYear}|${row.datasetType}`];
      const prose = `${f.headline} ${f.summary} ${f.whatThisMeans} ${f.entries.map((e) => e.text).join(' ')}`;
      // ⚠ THE TRAILING-PUNCTUATION TRAP: `[\d,.]+` swallows the full stop that
      // ends the sentence, so a correct "$15,042,917" is reported as the
      // unmeasured figure "$15,042,917.". Cents are genuinely possible in this
      // data, so the fraction part is matched explicitly instead of lumped in.
      //
      // ⚠⚠ AND A COMMA DOES THE SAME THING, which `[\d,]+` did NOT catch — it
      // is inside the class. "worth $77,446,980, are held in" matched
      // "$77,446,980," and reported a measured figure as unmeasured. Found by
      // the fiscal-period rule below, and fixed here too: the integer part must
      // END on a digit.
      const money = prose.match(/\$[\d,]*\d(?:\.\d+)?(?: (?:million|billion))?/g) ?? [];
      expect(money.length, `${row.id} states no figure at all`).toBeGreaterThan(0);
      const allowed = new Set([
        formatMoneyExact(row.total), formatMoneyExact(row.bondAmount),
        formatMoneyProse(row.total), formatMoneyProse(row.bondAmount),
      ]);
      for (const m of money) {
        expect(allowed.has(m), `${row.id} states ${m}, which is not this year's total or bond amount`)
          .toBe(true);
      }
    }
  });

  it('⚠ every stated percentage is the measured share', () => {
    for (const row of BOND_FINANCED_YEARS) {
      const f = emitted[`${row.entity}|${row.state}|${row.fiscalYear}|${row.datasetType}`];
      const prose = `${f.headline} ${f.summary} ${f.whatThisMeans} ${f.entries.map((e) => e.text).join(' ')}`;
      for (const pct of prose.match(/\d+(?:\.\d+)?%/g) ?? []) {
        expect(pct, row.id).toBe(`${bondSharePct(row)}%`);
      }
    }
  });

  it('⚠ every emitted year actually crosses the published threshold', () => {
    // A register row that does not meet its own rule is a banner telling a
    // reader something untrue about a government.
    for (const row of BOND_FINANCED_YEARS) {
      expect(row.total, row.id).toBeGreaterThan(0);
      expect(row.bondAmount / row.total, row.id).toBeGreaterThan(BOND_SHARE_THRESHOLD);
    }
  });

  it('⚠⚠ claims nothing about neighbouring years', () => {
    // Several entities are flagged in MORE THAN ONE year — Vernon in FY2003,
    // FY2012 and FY2016; Albany in FY2003 and FY2008 — so copy reading "unlike
    // the years around it" would be flatly false for them. Proven, not assumed:
    const multi = new Map<string, number>();
    for (const r of BOND_FINANCED_YEARS) {
      const k = `${r.entity}|${r.state}`;
      multi.set(k, (multi.get(k) ?? 0) + 1);
    }
    expect([...multi.values()].some((n) => n > 1)).toBe(true);

    const forbidden = /unlike the years|years on either side|years around it|neither year/i;
    for (const [key, f] of Object.entries(emitted)) {
      const prose = `${f.headline} ${f.summary} ${f.whatThisMeans}`;
      expect(forbidden.test(prose), `${key} makes a claim about adjacent years`).toBe(false);
    }
  });

  it('⚠ the reader is told the threshold, so they can apply their own', () => {
    const f = emitted['West Hollywood|CA|2016|revenue'];
    const prose = `${f.summary} ${f.entries.map((e) => e.text).join(' ')}`;
    expect(/quarter/i.test(prose), 'the banner never states the rule it was flagged by').toBe(true);
    expect(BOND_SHARE_THRESHOLD).toBe(0.25);
  });
});

/**
 * ⭐⭐⭐ THE PERIOD RULES — six hand-written entries, measured instead.
 *
 * West Hollywood had five straddle banners and McKinney an eleven-month
 * banner, every one of them written because a person spent a day on that city.
 * These guards fix what the replacements may do, because a rule writes copy for
 * every government at once and nobody reads every sentence it produces.
 */
describe('fiscal-period rules', () => {
  const emitted = fiscalPeriodFlags();
  const keyOf = (r) => `${r.entity}|${r.state}|${r.fiscalYear}|${r.datasetType}`;
  const proseOf = (f) =>
    `${f.headline} ${f.summary} ${f.whatThisMeans} ${f.entries.map((e) => e.text).join(' ')}`;

  it('⭐⭐ reproduces every hand-written banner it replaced', () => {
    // The whole bargain: the rule replaces a judgement WITHOUT changing what a
    // reader sees. If this ever fails, the threshold moved and somebody must
    // look at who gained or lost a banner.
    for (const fy of [2019, 2020, 2024, 2025, 2026]) {
      expect(figureFlagFor('West Hollywood', 'CA', fy, 'transactions'), `WeHo FY${fy}`).toBeTruthy();
    }
    expect(figureFlagFor('McKinney', 'TX', 2026, 'transactions')).toBeTruthy();

    // ⚠ And the years whose skew is below the published threshold stay
    // unflagged, or the ones that matter stop standing out. FY2017 is the
    // closest call at 6.6% and was deliberately left out.
    for (const fy of [2017, 2018, 2021, 2022, 2023]) {
      expect(figureFlagFor('West Hollywood', 'CA', fy, 'transactions'), `WeHo FY${fy}`).toBeUndefined();
    }
  });

  it('⚠⚠⚠ no hand-written entry survives for a year a rule now covers', () => {
    // `figureFlags` merges rule-emitted with hand-written and HAND-WRITTEN
    // WINS. An entry left behind would silently suppress its own replacement
    // and the migration would be decorative — the banner would still be a
    // record of who was looking.
    const authored = Object.keys(figureFlags).filter((k) => !(k in emitted));
    const overlaps = authored.filter((k) => /^(West Hollywood\|CA|McKinney\|TX)\|\d+\|transactions$/.test(k));
    expect(overlaps, `still hand-written: ${overlaps.join(', ')}`).toEqual([]);
  });

  it('⚠⚠ emits no key a hand-written flag already owns', () => {
    const authored = new Set(Object.keys(figureFlags).filter((k) => !(k in emitted)));
    const collisions = Object.keys(emitted).filter((k) => authored.has(k));
    expect(collisions, `rule and author both claim: ${collisions.join(', ')}`).toEqual([]);
  });

  it('⚠⚠ the two period rules never claim the same key', () => {
    // Only one banner renders per key, so a collision silently costs a reader
    // whichever sentence lost the merge. ⭐ This is a live near-miss, not a
    // hypothetical: West Hollywood FY2025 has no July 2024 payment of its own
    // and would be an absent-month year, except that the month sits in the
    // FY2022-24 register — displaced, not absent.
    const distorted = new Set(FISCAL_PERIOD_DISTORTION_YEARS.map(keyOf));
    const both = ABSENT_MONTH_YEARS.map(keyOf).filter((k) => distorted.has(k));
    expect(both, `both period rules claim: ${both.join(', ')}`).toEqual([]);
    expect(Object.keys(emitted).length)
      .toBe(FISCAL_PERIOD_DISTORTION_YEARS.length + ABSENT_MONTH_YEARS.length);
  });

  it('⭐⭐ asks the whole series, not the cities somebody visited', () => {
    // The register records the denominator it was measured over, and it must
    // be bigger than the set it found — otherwise the rule only ever looked at
    // the years that were already flagged.
    expect(PERIOD_FLEET_SIZE).toBeGreaterThan(
      FISCAL_PERIOD_DISTORTION_YEARS.length + ABSENT_MONTH_YEARS.length);

    // ⭐⭐⭐ THE YEAR NOBODY HAD FLAGGED. Frisco FY2021 holds ten months: its
    // file stops on 2021-07-29 and is drawn beside two complete years. Frisco
    // has its own anomaly register AND its own row-coverage baseline, and
    // neither asked this question. If this assertion ever has to be deleted,
    // read the diff first — it is the proof that the rule beat the attention.
    const frisco = ABSENT_MONTH_YEARS.find((r) => r.entity === 'Frisco' && r.fiscalYear === 2021);
    expect(frisco, 'Frisco FY2021 is no longer measured as incomplete').toBeTruthy();
    expect(frisco.monthsCovered).toBe(10);
    expect(frisco.absentMonths).toEqual(['August 2021', 'September 2021']);
  });

  it('⚠⚠⚠ states no figure that is not measured', () => {
    // THE defect this architecture exists to prevent (PR #364): a banner that
    // hard-codes a number drifts from the chart beside it. Every money figure
    // in the prose must come from the row it describes.
    //
    // ⚠⚠ THE TRAILING-PUNCTUATION TRAP, AND THE COMMA IS THE ONE THAT BIT.
    // `[\d,]+` includes the comma, so "worth $77,446,980, are held in" matched
    // "$77,446,980," and this test reported a correctly measured figure as
    // unmeasured. The integer part must END on a digit. (The bond rule's copy
    // happened never to put a comma after a figure, so its version of this
    // guard carried the same hole untripped.)
    const money = (s) => s.match(/\$[\d,]*\d(?:\.\d+)?(?: (?:million|billion))?/g) ?? [];
    const forms = (...n) => new Set(n.flatMap((x) => [formatMoneyExact(x), formatMoneyProse(x)]));

    for (const row of FISCAL_PERIOD_DISTORTION_YEARS) {
      const f = emitted[keyOf(row)];
      const allowed = forms(row.total, row.outAmount, row.elsewhereAmount);
      const found = money(proseOf(f));
      expect(found.length, `${row.id} states no figure at all`).toBeGreaterThan(0);
      for (const m of found) {
        expect(allowed.has(m), `${row.id} states ${m}, which is not a figure measured for this year`)
          .toBe(true);
      }
    }

    for (const row of ABSENT_MONTH_YEARS) {
      const f = emitted[keyOf(row)];
      // ⚠ The SAME selection the copy makes — nearest complete year, not most
      // recent. When this test kept its own copy of that choice it went green
      // on a sentence the rule had stopped writing.
      const control = nearestCompleteYear(row);
      const allowed = forms(
        row.total,
        perMonth(row.total, row.monthsCovered),
        ...(control ? [control.total, perMonth(control.total, row.monthsInPeriod)] : []),
      );
      const found = money(proseOf(f));
      expect(found.length, `${row.id} states no figure at all`).toBeGreaterThan(0);
      for (const m of found) {
        expect(allowed.has(m), `${row.id} states ${m}, which is not a figure measured for this year`)
          .toBe(true);
      }
    }
  });

  it('⚠ every stated percentage is the measured share', () => {
    for (const row of FISCAL_PERIOD_DISTORTION_YEARS) {
      const f = emitted[keyOf(row)];
      for (const pct of proseOf(f).match(/\d+(?:\.\d+)?%/g) ?? []) {
        expect(pct, row.id).toBe(`${distortionPctText(row)}%`);
      }
    }
  });

  it('⚠ every emitted year actually crosses the published threshold', () => {
    // A register row that does not meet its own rule is a banner telling a
    // reader something untrue about a government.
    for (const row of FISCAL_PERIOD_DISTORTION_YEARS) {
      expect(row.total, row.id).toBeGreaterThan(0);
      expect(Math.max(row.ownShare, row.displacedShare), row.id)
        .toBeGreaterThan(PERIOD_DISTORTION_THRESHOLD);
      // The axis the copy speaks from must be the one that qualified.
      const share = row.axis === 'own' ? row.ownShare : row.displacedShare;
      expect(share, `${row.id} leads with the axis that did not cross`)
        .toBeGreaterThan(PERIOD_DISTORTION_THRESHOLD);
    }
    for (const row of ABSENT_MONTH_YEARS) {
      expect(row.monthsCovered, row.id).toBeLessThan(row.monthsInPeriod);
      expect(row.absentMonths.length, row.id).toBe(row.monthsInPeriod - row.monthsCovered);
    }
  });

  it('⚠ the reader is told the threshold, so they can apply their own', () => {
    for (const row of FISCAL_PERIOD_DISTORTION_YEARS) {
      const f = emitted[keyOf(row)];
      const prose = `${f.summary} ${f.entries.map((e) => e.text).join(' ')}`;
      expect(/more than a tenth/i.test(prose), `${row.id} never states the rule it was flagged by`)
        .toBe(true);
    }
    // ⚠ The words and the number must mean the same thing. "More than a tenth"
    // beside a threshold of 0.25 would be a lie a reader cannot detect.
    expect(PERIOD_DISTORTION_THRESHOLD).toBe(0.10);
  });

  it('⚠⚠ claims nothing about neighbouring years it has not measured', () => {
    // West Hollywood is flagged in FY2019 AND FY2020, FY2024 AND FY2025 AND
    // FY2026, so copy reading "unlike the years around it" is flatly false.
    // Proven, not assumed:
    const multi = new Map<string, number>();
    for (const r of [...FISCAL_PERIOD_DISTORTION_YEARS, ...ABSENT_MONTH_YEARS]) {
      const k = `${r.entity}|${r.state}`;
      multi.set(k, (multi.get(k) ?? 0) + 1);
    }
    expect([...multi.values()].some((n) => n > 1)).toBe(true);

    const forbidden = /unlike the years|years on either side|years around it|neither year/i;
    for (const [key, f] of Object.entries(emitted)) {
      expect(forbidden.test(proseOf(f)), `${key} makes a claim about adjacent years`).toBe(false);
    }
  });

  it('⚠⚠ never says WHY a month or a payment is where it is', () => {
    // ⛔ THE LINE BETWEEN A FACT AND AN INFERENCE. "McKinney has not posted
    // September yet" is the obvious reading and may well be right, and it is
    // still a guess about a government's internal process. Frisco's sibling
    // register is held back from readers for exactly this reason; a rule that
    // speculated would walk straight past that line for every city at once.
    const speculation = /\b(has not (yet )?(posted|published|released)|not yet (posted|published|released)|delayed|late|behind schedule|forgot|failed to)\b/i;
    for (const [key, f] of Object.entries(emitted)) {
      expect(speculation.test(proseOf(f)), `${key} speculates about the publisher`).toBe(false);
    }
  });

  it('⚠⚠⚠ an absent-month flag carries a MECHANICAL retirement condition', () => {
    // The whole reason this rule exists. McKinney's hand-written entry stated
    // its retirement condition in prose for a human to act on, and the banner
    // becomes FALSE the day the city posts September. Here the condition is
    // the rule itself — but the register must still SAY what it is waiting
    // for, naming the months, so a reader of the register knows.
    expect(ABSENT_MONTH_YEARS.length).toBeGreaterThan(0);
    for (const row of ABSENT_MONTH_YEARS) {
      expect(row.retireWhen, `${row.id} has no retirement condition`).toBeTruthy();
      for (const month of row.absentMonths) {
        expect(row.retireWhen, `${row.id} does not name ${month}`).toContain(month);
      }
      expect(row.retireWhen, `${row.id} does not name the file it is waiting on`)
        .toContain(row.sourceName);
    }
  });

  it('⚠⚠ the out-of-period register no longer decides who is flagged', () => {
    // It used to hand-type `readerFacing` per year, which made it a SECOND
    // authority beside src/data/figureFlags.ts for one decision. Both are gone;
    // the published threshold decides and the register reads it. This proves
    // they cannot drift apart again.
    const flagged = new Set(FISCAL_PERIOD_DISTORTION_YEARS.map((r) => r.id));
    for (const e of OUT_OF_PERIOD_EXCEPTIONS) {
      if (!String(e.id ?? '').endsWith('-fiscal-straddle')) continue;
      expect(e.readerFacing, `${e.id} disagrees with the rule about being reader-facing`)
        .toBe(flagged.has(e.id));
    }
  });

  it('⚠ a hand-declared stillGrowing and the measured one agree', () => {
    // `stillGrowing` is declared by hand in the out-of-period register (it
    // describes TT's SYNC configuration, not the publisher's figures) and
    // derived independently by the rule from is_enabled + a non-manual sync
    // frequency + being the newest year. Two derivations of one fact drift
    // unless something holds them together.
    const measured = new Map(FISCAL_PERIOD_DISTORTION_YEARS.map((r) => [r.id, r.stillGrowing]));
    for (const e of OUT_OF_PERIOD_EXCEPTIONS) {
      if (!measured.has(e.id)) continue;
      expect(measured.get(e.id), `${e.id}: register says stillGrowing=${e.stillGrowing === true}`)
        .toBe(e.stillGrowing === true);
    }
  });
});
